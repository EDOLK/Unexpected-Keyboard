#!/usr/bin/env python3
"""Build the word pairs files for every dictionary supported by the app and
the list the app downloads them from.

Usage: build_bigrams.py AOSP_DICTIONARIES_DIR OUT_DIR

AOSP_DICTIONARIES_DIR is a checkout of
https://codeberg.org/Helium314/aosp-dictionaries, the source of the word
lists the dictionaries are built from.

Writes OUT_DIR/v1/<dict name>.bigrams, gzip compressed like the dictionaries,
and res/values/bigrams.xml, which lists the files with the size and SHA-256
of the uncompressed data.
"""

import base64
import gzip
import hashlib
import os
import re
import subprocess
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
FORMAT_VERSION = 1
# Ignore word lists with too few pairs to be useful.
MIN_PAIRS = 1000
# Close variants whose pairs are used when they have more pairs than the
# dictionary's own word list, which might have none.
FALLBACKS = { "en_AU": "en_US", "en_CA": "en_US", "en_GB": "en_US" }


def app_dictionaries():
  x = open(os.path.join(ROOT, "res/values/dictionaries.xml"), encoding="utf-8").read()
  arr = x.split('name="dictionaries_locale"')[1].split("</string-array>")[0]
  return re.findall(r"<item>([^<]+)</item>", arr)


def count_pairs(path):
  with open(path, encoding="utf-8") as f:
    return sum(1 for line in f if line.lstrip().startswith("bigram="))


def source_for(aosp, name):
  """The word list with the most pairs for [name], or None."""
  names = [name] + ([FALLBACKS[name]] if name in FALLBACKS else [])
  best, best_n = None, 0
  for n_ in names:
    for f in ("main_%s.combined" % n_, "main_%s__experimental.combined" % n_):
      p = os.path.join(aosp, "wordlists", f)
      if os.path.exists(p):
        n = count_pairs(p)
        if n > best_n:
          best, best_n = p, n
  return best if best_n >= MIN_PAIRS else None


def main():
  if len(sys.argv) != 3:
    sys.exit(__doc__.split("\n\n")[1])
  aosp, out_dir = sys.argv[1:]
  version_dir = os.path.join(out_dir, "v%d" % FORMAT_VERSION)
  os.makedirs(version_dir, exist_ok=True)
  built = []
  for name in app_dictionaries():
    src = source_for(aosp, name)
    if src is None:
      continue
    raw = os.path.join(version_dir, name + ".bigrams.raw")
    subprocess.run([sys.executable, os.path.join(ROOT, "scripts/gen_bigrams.py"),
                    name, src, raw], check=True)
    data = open(raw, "rb").read()
    os.remove(raw)
    # mtime=0 for reproducible files
    with open(os.path.join(version_dir, name + ".bigrams"), "wb") as f:
      f.write(gzip.compress(data, compresslevel=9, mtime=0))
    sha = base64.b64encode(hashlib.sha256(data).digest()).decode()
    built.append((name, len(data), sha, os.path.basename(src)))
  write_res(built)
  with open(os.path.join(version_dir, "SOURCES"), "w") as f:
    for name, _, _, src in built:
      f.write("%s %s\n" % (name, src))
  print("Built %d word pairs files" % len(built))


def write_res(built):
  def arr(kind, name, values):
    items = "".join("    <item>%s</item>\n" % v for v in values)
    return '  <%s-array name="%s">\n%s  </%s-array>\n' % (kind, name, items, kind)
  with open(os.path.join(ROOT, "res/values/bigrams.xml"), "w", encoding="utf-8") as f:
    f.write("<?xml version='1.0' encoding='utf-8'?>\n<resources>\n")
    f.write("  <!-- Generated by scripts/build_bigrams.py. Word pairs available for\n"
            "       download, see [DictionaryListView.BIGRAMS_REPO_URL]. Sizes and\n"
            "       checksums are of the uncompressed files. -->\n")
    f.write(arr("string", "bigrams_dict_name", [b[0] for b in built]))
    f.write(arr("integer", "bigrams_size", [b[1] for b in built]))
    f.write(arr("string", "bigrams_sha256", [b[2] for b in built]))
    f.write("</resources>\n")


if __name__ == "__main__":
  main()
